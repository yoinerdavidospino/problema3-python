# Matriz de inventario
inventario = [
    [101, "Teclado", 5, 10],
    [102, "Mouse", 8, 8],
    [103, "Monitor", 2, 5],
    [104, "USB", 15, 10],
    [105, "Impresora", 1, 4]
]

# Función para calcular cantidad a pedir
def cantidad_pedir(stock_actual, stock_minimo):
    if stock_actual < stock_minimo:
        return stock_minimo - stock_actual
    else:
        return 0

print("REPORTE DE REABASTECIMIENTO")

for articulo in inventario:
    nombre = articulo[1]
    stock_actual = articulo[2]
    stock_minimo = articulo[3]

    pedido = cantidad_pedir(stock_actual, stock_minimo)

    print("Artículo:", nombre)
    print("Cantidad a pedir:", pedido)
    print("-------------------")